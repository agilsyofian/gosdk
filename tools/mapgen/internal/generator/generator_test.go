// e2eModule synthesizes a temp module that depends on mapgen through a
// replace directive pointing at this repository.
func e2eModule(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	for _, sub := range []string{"model", "pb", "converters", "handler"} {
		if err := os.Mkdir(filepath.Join(dir, sub), 0o750); err != nil {
			t.Fatal(err)
		}
	}
	writeFile(t, dir, "go.mod", `module example.com/app

go 1.25

require github.com/agilsyofian/gosdk/utils/mapgen v0.0.0

replace github.com/agilsyofian/gosdk/utils/mapgen => `+root+`
`)
	writeFile(t, filepath.Join(dir, "model"), "model.go", `package model

type UserID int64

type Employee struct {
	ID   UserID `+"`map:\"Id\"`"+`
	Name string
	Age  int32
}
`)
	writeFile(t, filepath.Join(dir, "pb"), "pb.go", `package pb

type Employee struct {
	state int
	Id    string
	Name  string
	Age   int32
}

func (x *Employee) GetId() string {
	if x != nil {
		return x.Id
	}
	return ""
}

func (x *Employee) GetName() string {
	if x != nil {
		return x.Name
	}
	return ""
}

func (x *Employee) GetAge() int32 {
	if x != nil {
		return x.Age
	}
	return 0
}
`)
	writeFile(t, filepath.Join(dir, "converters"), "converters.go", `package converters

import (
	"strconv"

	"github.com/agilsyofian/gosdk/utils/mapgen/runtime/mapper"

	"example.com/app/model"
)

func init() {
	mapper.Register(FormatUserID)
	mapper.RegisterE(ParseUserID)
}

func FormatUserID(id model.UserID) string {
	return strconv.FormatInt(int64(id), 10)
}

func ParseUserID(s string) (model.UserID, error) {
	n, err := strconv.ParseInt(s, 10, 64)
	return model.UserID(n), err
}
`)
	writeFile(t, filepath.Join(dir, "handler"), "handler.go", `package handler

import (
	"example.com/app/model"
	"example.com/app/pb"
)

var (
	_ model.Employee
	_ pb.Employee
)
`)
	return dir
}

func e2eEnv(dir string) generator.Env {
	return generator.Env{
		GoFile:    "handler.go",
		GoPackage: "handler",
		Dir:       filepath.Join(dir, "handler"),
	}
}

func e2eConfig() cli.Config {
	return cli.Config{
		Pairs: []cli.TypePair{{
			Src: cli.TypeRef{Pkg: "model", Name: "Employee"},
			Dst: cli.TypeRef{Pkg: "pb", Name: "Employee", Pointer: true},
		}},
		ConverterPkgs: []string{"../converters"},
		Output:        ".",
		Direction:     cli.DirectionBoth,
	}
}

func TestRun(t *testing.T) {
	// Make the temp module resolvable offline: mapgen's dependencies are
	// already in the local module cache.
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOSUMDB", "off")
	t.Setenv("GOPROXY", "off")
	dir := e2eModule(t)
	env := e2eEnv(dir)

	if err := generator.Run(e2eConfig(), env); err != nil {
		t.Fatalf("run: %v", err)
	}

	outPath := filepath.Join(dir, "handler", "handler_gen.go")
	out, err := os.ReadFile(filepath.Clean(outPath))
	if err != nil {
		t.Fatalf("read output: %v", err)
	}
	for _, want := range []string{
		"// Code generated by mapgen. DO NOT EDIT.",
		"func EmployeeToPb(src model.Employee) *pb.Employee {",
		"func EmployeeFromPb(src *pb.Employee) (model.Employee, error) {",
		"converters.FormatUserID(src.ID)",
	} {
		if !strings.Contains(string(out), want) {
			t.Errorf("output does not contain %q\n%s", want, out)
		}
	}

	// The generated file must type-check as part of the temp module.
	loadCfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedImports |
			packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo,
		Dir: dir,
	}
	pkgs, err := packages.Load(loadCfg, "./...")
	if err != nil {
		t.Fatalf("reload module: %v", err)
	}
	var loadErrs []error
	packages.Visit(pkgs, nil, func(p *packages.Package) {
		for _, e := range p.Errors {
			loadErrs = append(loadErrs, errors.New(e.Error()))
		}
	})
	if len(loadErrs) > 0 {
		t.Fatalf("generated module does not compile: %v\n%s", errors.Join(loadErrs...), out)
	}

	// Running again with identical inputs must be a no-op.
	before, err := os.Stat(outPath)
	if err != nil {
		t.Fatal(err)
	}
	if err := generator.Run(e2eConfig(), env); err != nil {
		t.Fatalf("second run: %v", err)
	}
	after, err := os.Stat(outPath)
	if err != nil {
		t.Fatal(err)
	}
	if !after.ModTime().Equal(before.ModTime()) {
		t.Error("unchanged output was rewritten")
	}
}

func TestRunCheck(t *testing.T) {
	// Make the temp module resolvable offline: mapgen's dependencies are
	// already in the local module cache.
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOSUMDB", "off")
	t.Setenv("GOPROXY", "off")
	dir := e2eModule(t)
	env := e2eEnv(dir)

	cfg := e2eConfig()
	cfg.Check = true

	// Missing output: out of date.
	if err := generator.Run(cfg, env); err == nil || !strings.Contains(err.Error(), "out of date") {
		t.Fatalf("expected out-of-date error, got %v", err)
	}

	if err := generator.Run(e2eConfig(), env); err != nil {
		t.Fatalf("generate: %v", err)
	}
	if err := generator.Run(cfg, env); err != nil {
		t.Fatalf("check after generate: %v", err)
	}

	// Stale output: out of date.
	outPath := filepath.Join(dir, "handler", "handler_gen.go")
	stale := []byte("// Code generated by mapgen. DO NOT EDIT.\n\npackage handler\n")
	if err := os.WriteFile(outPath, stale, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := generator.Run(cfg, env); err == nil || !strings.Contains(err.Error(), "out of date") {
		t.Fatalf("expected out-of-date error, got %v", err)
	}
}

func TestRunDuplicateConverterPkgs(t *testing.T) {
	// Make the temp module resolvable offline: mapgen's dependencies are
	// already in the local module cache.
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOSUMDB", "off")
	t.Setenv("GOPROXY", "off")
	dir := e2eModule(t)
	env := e2eEnv(dir)

	cfg := e2eConfig()
	// The same package through a directory path and an import path must
	// be scanned only once.
	cfg.ConverterPkgs = []string{"../converters", "example.com/app/converters"}
	if err := generator.Run(cfg, env); err != nil {
		t.Fatalf("run: %v", err)
	}
}

func TestRunCreatesOutputDir(t *testing.T) {
	// Make the temp module resolvable offline: mapgen's dependencies are
	// already in the local module cache.
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOSUMDB", "off")
	t.Setenv("GOPROXY", "off")
	dir := e2eModule(t)
	env := e2eEnv(dir)

	cfg := e2eConfig()
	cfg.Output = "./gen"
	cfg.Package = "gen"
	if err := generator.Run(cfg, env); err != nil {
		t.Fatalf("run: %v", err)
	}

	out, err := os.ReadFile(filepath.Clean(filepath.Join(dir, "handler", "gen", "handler_gen.go")))
	if err != nil {
		t.Fatalf("read output: %v", err)
	}
	for _, want := range []string{"// Code generated by mapgen. DO NOT EDIT.", "package gen"} {
		if !strings.Contains(string(out), want) {
			t.Errorf("output does not contain %q\n%s", want, out)
		}
	}
}

func TestRunRefusesForeignFile(t *testing.T) {
	// Make the temp module resolvable offline: mapgen's dependencies are
	// already in the local module cache.
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOSUMDB", "off")
	t.Setenv("GOPROXY", "off")
	dir := e2eModule(t)
	env := e2eEnv(dir)

	writeFile(t, filepath.Join(dir, "handler"), "handler_gen.go", `package handler
`)
	err := generator.Run(e2eConfig(), env)
	if err == nil || !strings.Contains(err.Error(), "refusing to overwrite") {
		t.Fatalf("expected refusal, got %v", err)
	}
}
